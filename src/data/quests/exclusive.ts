import type { AuthoredQuestDefinition, MoodId } from "../questTypes";

type ExclusiveRow = readonly [
  id: string,
  moods: readonly MoodId[],
  enName: string,
  en: string,
  deName: string,
  de: string,
];

function forGame(
  gameId: string,
  name: string,
  rows: readonly ExclusiveRow[],
): AuthoredQuestDefinition[] {
  return rows.map(([id, moodIds, enName, en, deName, de]) => ({
    id: `${gameId}-${id}`,
    moodIds,
    universal: false,
    minimumDurationMinutes: 5,
    suggestedDurationMinutes: 25,
    genres: [],
    translations: {
      en: {
        name: enName,
        objective: `In **${name}**: ${en}`,
        gameObjective: `In **{{game}}**: ${en}`,
      },
      de: {
        name: deName,
        objective: `In **${name}**: ${de}`,
        gameObjective: `In **{{game}}**: ${de}`,
      },
    },
  }));
}

