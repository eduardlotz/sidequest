import type { CuratedGameDefinition, GameCapabilityId } from "../gameTypes";
import { QUEST_CORES } from "../quests";
import { matchesGameCapabilities } from "../gameCompatibility";
import { exclusiveQuestsByGame } from "../quests/exclusive";

function game(
  id: keyof typeof exclusiveQuestsByGame,
  name: string,
  capabilityIds: readonly GameCapabilityId[],
  isSeries = false,
  compatibleQuestIds: readonly string[] = [],
  exclusiveQuestIds: readonly string[] = [],
): CuratedGameDefinition {
  const capabilities = new Set(capabilityIds);
  return {
    id,
    name,
    artwork: `games/${id}.jpg`,
    isSeries,
    compatibleQuestIds: Array.from(
      new Set([
        ...QUEST_CORES.filter(
          (quest) =>
            quest.gameBindable &&
            matchesGameCapabilities(
              capabilities,
              quest.customGameCompatibility,
            ),
        ).map((quest) => quest.id),
        ...compatibleQuestIds,
      ]),
    ),
    exclusiveQuestIds: [
      ...exclusiveQuestIds,
      ...exclusiveQuestsByGame[id].map((quest) => quest.id),
    ],
  };
}

